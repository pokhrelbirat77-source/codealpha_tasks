def extract_cylinders(value):
    text = str(value).lower()

    match = re.search(r"(\d+)\s*cylinder", text)
    if match:
        return int(match.group(1))

    match = re.search(r"\bv(\d+)\b", text)
    if match:
        return int(match.group(1))

    match = re.search(r"\bi(\d+)\b", text)
    if match:
        return int(match.group(1))

    return np.nan

