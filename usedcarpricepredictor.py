def simplify_transmission(value):
    text = str(value).lower().strip()

    # Manual
    if "manual" in text or "m/t" in text or "mt" in text:
        return "Manual"

    # Automatic
    if (
        "automatic" in text
        or "a/t" in text
        or "at" in text
        or "cvt" in text
        or "dual shift" in text
        or "cmdshft" in text
        or "overdrive" in text
        or "single-speed fixed gear" in text
    ):
        return "Automatic"

    return "Other"

