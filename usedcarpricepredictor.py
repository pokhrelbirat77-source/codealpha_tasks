import joblib

# IMPORTANT FOR DEPLOYMENT
# ------------------------
# Do not save ``model`` and ``preprocessor`` as separate files.  The Streamlit
# app must apply the *fitted* preprocessor before calling the regressor, in
# exactly this order.  Saving one Pipeline makes that order part of the model
# artifact and prevents feature-shape/preprocessing mismatches at prediction
# time.
used_car_price_pipeline = Pipeline([
    ("preprocessor", preprocessor),
    ("model", XGBRegressor(
        n_estimators=200,
        learning_rate=0.05,
        max_depth=5,
        random_state=42,
        objective="reg:squarederror"
    ))
])

# ``y_train`` is log1p(price), so pipeline.predict returns log1p(price).
# The app converts it back with np.expm1 before showing the dollar value.
used_car_price_pipeline.fit(X_train, y_train)

pipeline_predictions = np.expm1(used_car_price_pipeline.predict(X_test))
